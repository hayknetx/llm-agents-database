-- =====================================================================
-- 4. QUERIES
-- =====================================================================

-- Q1. Display all users.
SELECT *
FROM USERS
ORDER BY USER_ID;

-- Q2. Display all models with their provider and prices.
SELECT MODEL_NAME, PROVIDER, CONTEXT_WINDOW, INPUT_PRICE, OUTPUT_PRICE
FROM MODELS
ORDER BY MODEL_ID;

-- Q3. Display all agents with the owner's name and the model name.
SELECT
    A.AGENT_ID,
    A.AGENT_NAME,
    U.FIRST_NAME || ' ' || U.LAST_NAME AS OWNER_NAME,
    M.MODEL_NAME,
    A.TEMPERATURE
FROM AGENTS A
JOIN USERS U
    ON A.USER_ID = U.USER_ID
JOIN MODELS M
    ON A.MODEL_ID = M.MODEL_ID
ORDER BY A.AGENT_ID;

-- Q4. Display all tools available to a selected agent (agent 2).
SELECT
    T.TOOL_ID,
    T.TOOL_NAME,
    T.TOOL_TYPE,
    T.DESCRIPTION
FROM AGENT_TOOLS AGT
JOIN TOOLS T
    ON AGT.TOOL_ID = T.TOOL_ID
WHERE AGT.AGENT_ID = 2
ORDER BY T.TOOL_ID;

-- Q5. Display all runs of a selected agent (agent 2), ordered by start time.
SELECT RUN_ID, TASK_DESCRIPTION, START_TIME, END_TIME, STATUS
FROM RUNS
WHERE AGENT_ID = 2
ORDER BY START_TIME;

-- Q6. Count how many runs each agent has (agents with no runs show 0).
SELECT
    A.AGENT_ID,
    A.AGENT_NAME,
    COUNT(R.RUN_ID) AS RUN_COUNT
FROM AGENTS A
LEFT JOIN RUNS R
    ON A.AGENT_ID = R.AGENT_ID
GROUP BY
    A.AGENT_ID,
    A.AGENT_NAME
ORDER BY A.AGENT_ID;

-- Q7. Display all failed runs with the agent name.
SELECT
    R.RUN_ID,
    A.AGENT_NAME,
    R.TASK_DESCRIPTION,
    R.START_TIME
FROM RUNS R
JOIN AGENTS A
    ON R.AGENT_ID = A.AGENT_ID
WHERE R.STATUS = 'FAILED'
ORDER BY R.RUN_ID;

-- Q8. Display models with a context window larger than 100000 tokens.
SELECT MODEL_NAME, PROVIDER, CONTEXT_WINDOW
FROM MODELS
WHERE CONTEXT_WINDOW > 100000
ORDER BY CONTEXT_WINDOW DESC;

-- Q9. Calculate the cost of each run in USD from its tokens and the model's prices.
--     cost = (input tokens * input price + output tokens * output price) / 1 000 000
SELECT
    R.RUN_ID,
    A.AGENT_NAME,
    M.MODEL_NAME,
    R.INPUT_TOKENS,
    R.OUTPUT_TOKENS,
    ROUND((R.INPUT_TOKENS * M.INPUT_PRICE + R.OUTPUT_TOKENS * M.OUTPUT_PRICE) / 1000000, 4) AS COST_USD
FROM RUNS R
JOIN AGENTS A
    ON R.AGENT_ID = A.AGENT_ID
JOIN MODELS M
    ON A.MODEL_ID = M.MODEL_ID
ORDER BY R.RUN_ID;

-- Q10. Total tokens and total cost for each user (users with no runs show 0).
SELECT
    U.USER_ID,
    U.FIRST_NAME || ' ' || U.LAST_NAME AS USER_NAME,
    COUNT(R.RUN_ID) AS RUN_COUNT,
    NVL(SUM(R.INPUT_TOKENS + R.OUTPUT_TOKENS), 0) AS TOTAL_TOKENS,
    NVL(ROUND(SUM(R.INPUT_TOKENS * M.INPUT_PRICE + R.OUTPUT_TOKENS * M.OUTPUT_PRICE) / 1000000, 4), 0) AS TOTAL_COST_USD
FROM USERS U
LEFT JOIN AGENTS A
    ON U.USER_ID = A.USER_ID
LEFT JOIN MODELS M
    ON A.MODEL_ID = M.MODEL_ID
LEFT JOIN RUNS R
    ON A.AGENT_ID = R.AGENT_ID
GROUP BY
    U.USER_ID,
    U.FIRST_NAME,
    U.LAST_NAME
ORDER BY TOTAL_COST_USD DESC;

-- Q11. How many times each tool was called, with errors, timeouts and average duration
--      (tools that were never called show 0).
SELECT
    T.TOOL_NAME,
    COUNT(C.CALL_ID) AS TOTAL_CALLS,
    COUNT(CASE WHEN C.CALL_STATUS = 'ERROR' THEN 1 END) AS ERRORS,
    COUNT(CASE WHEN C.CALL_STATUS = 'TIMEOUT' THEN 1 END) AS TIMEOUTS,
    ROUND(AVG(C.DURATION_MS)) AS AVG_DURATION_MS
FROM TOOLS T
LEFT JOIN TOOL_CALLS C
    ON T.TOOL_ID = C.TOOL_ID
GROUP BY T.TOOL_NAME
ORDER BY TOTAL_CALLS DESC, T.TOOL_NAME;

-- Q12. Display all tool calls with their run and agent details.
SELECT
    C.CALL_ID,
    C.RUN_ID,
    A.AGENT_NAME,
    R.TASK_DESCRIPTION,
    T.TOOL_NAME,
    C.CALL_TIME,
    C.DURATION_MS,
    C.CALL_STATUS
FROM TOOL_CALLS C
JOIN RUNS R
    ON C.RUN_ID = R.RUN_ID
JOIN AGENTS A
    ON R.AGENT_ID = A.AGENT_ID
JOIN TOOLS T
    ON C.TOOL_ID = T.TOOL_ID
ORDER BY C.CALL_ID;

-- Q13. Duration of each finished run in seconds, longest first.
SELECT
    RUN_ID,
    TASK_DESCRIPTION,
    STATUS,
    ROUND((CAST(END_TIME AS DATE) - CAST(START_TIME AS DATE)) * 24 * 60 * 60) AS DURATION_SECONDS
FROM RUNS
WHERE END_TIME IS NOT NULL
ORDER BY DURATION_SECONDS DESC;

-- Q14. Agents that have never been run.
SELECT A.AGENT_ID, A.AGENT_NAME
FROM AGENTS A
WHERE NOT EXISTS (
    SELECT 1
    FROM RUNS R
    WHERE R.AGENT_ID = A.AGENT_ID
);

-- Q15. Data check: tool calls that used a tool NOT assigned to the run's agent.
--      Should return no rows.
SELECT
    C.CALL_ID,
    R.AGENT_ID,
    C.TOOL_ID
FROM TOOL_CALLS C
JOIN RUNS R
    ON C.RUN_ID = R.RUN_ID
WHERE NOT EXISTS (
    SELECT 1
    FROM AGENT_TOOLS AGT
    WHERE AGT.AGENT_ID = R.AGENT_ID
      AND AGT.TOOL_ID = C.TOOL_ID
);


