-- 3. QUERIES

-- 1. All users
SELECT * FROM USERS;

-- 2. All models with provider and prices
SELECT MODEL_NAME, PROVIDER, INPUT_PRICE, OUTPUT_PRICE FROM MODELS;

-- 3. All agents with owner name and model name
SELECT A.AGENT_NAME, U.FIRST_NAME, U.LAST_NAME, M.MODEL_NAME
FROM AGENTS A
JOIN USERS U ON A.USER_ID = U.USER_ID
JOIN MODELS M ON A.MODEL_ID = M.MODEL_ID;

-- 4. Tools of agent 2
SELECT T.TOOL_NAME, T.TOOL_TYPE
FROM AGENT_TOOLS AGT
JOIN TOOLS T ON AGT.TOOL_ID = T.TOOL_ID
WHERE AGT.AGENT_ID = 2;

-- 5. Runs of agent 2, ordered by start time
SELECT * FROM RUNS
WHERE AGENT_ID = 2
ORDER BY START_TIME;

-- 6. Number of runs for each agent
SELECT A.AGENT_NAME, COUNT(R.RUN_ID) AS RUN_COUNT
FROM AGENTS A
LEFT JOIN RUNS R ON A.AGENT_ID = R.AGENT_ID
GROUP BY A.AGENT_NAME;

-- 7. Failed runs with agent name
SELECT R.RUN_ID, A.AGENT_NAME, R.TASK_DESCRIPTION
FROM RUNS R
JOIN AGENTS A ON R.AGENT_ID = A.AGENT_ID
WHERE R.STATUS = 'FAILED';

-- 8. Models with a context window larger than 100000
SELECT * FROM MODELS
WHERE CONTEXT_WINDOW > 100000;

-- 9. Cost of each run in USD
SELECT R.RUN_ID,
       (R.INPUT_TOKENS * M.INPUT_PRICE + R.OUTPUT_TOKENS * M.OUTPUT_PRICE) / 1000000 AS COST_USD
FROM RUNS R
JOIN AGENTS A ON R.AGENT_ID = A.AGENT_ID
JOIN MODELS M ON A.MODEL_ID = M.MODEL_ID;

-- 10. All tool calls with run and agent details
SELECT C.CALL_ID, A.AGENT_NAME, R.TASK_DESCRIPTION, T.TOOL_NAME, C.CALL_STATUS
FROM TOOL_CALLS C
JOIN RUNS R ON C.RUN_ID = R.RUN_ID
JOIN AGENTS A ON R.AGENT_ID = A.AGENT_ID
JOIN TOOLS T ON C.TOOL_ID = T.TOOL_ID
ORDER BY C.CALL_ID;
