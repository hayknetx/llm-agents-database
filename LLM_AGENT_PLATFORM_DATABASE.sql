-- LLM AGENT PLATFORM DATABASE (Oracle SQL)

-- 1. TABLES

CREATE TABLE USERS(
    USER_ID NUMBER PRIMARY KEY,
    FIRST_NAME VARCHAR2(30),
    LAST_NAME VARCHAR2(30),
    EMAIL VARCHAR2(255) NOT NULL UNIQUE,
    REGISTRATION_DATE DATE
);

CREATE TABLE MODELS(
    MODEL_ID NUMBER PRIMARY KEY,
    MODEL_NAME VARCHAR2(50) NOT NULL UNIQUE,
    PROVIDER VARCHAR2(50) NOT NULL,
    CONTEXT_WINDOW NUMBER CHECK (CONTEXT_WINDOW > 0),
    INPUT_PRICE NUMBER CHECK (INPUT_PRICE >= 0),
    OUTPUT_PRICE NUMBER CHECK (OUTPUT_PRICE >= 0)
);

CREATE TABLE AGENTS(
    AGENT_ID NUMBER PRIMARY KEY,
    USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID),
    MODEL_ID NUMBER NOT NULL REFERENCES MODELS(MODEL_ID),
    AGENT_NAME VARCHAR2(50) NOT NULL,
    SYSTEM_PROMPT VARCHAR2(1000),
    TEMPERATURE NUMBER CHECK (TEMPERATURE BETWEEN 0 AND 2),
    CREATED_DATE DATE
);

CREATE TABLE TOOLS(
    TOOL_ID NUMBER PRIMARY KEY,
    TOOL_NAME VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(255),
    TOOL_TYPE VARCHAR2(20) CHECK (TOOL_TYPE IN ('SEARCH','CODE','DATABASE','API','FILE'))
);

CREATE TABLE AGENT_TOOLS(
    AGENT_ID NUMBER REFERENCES AGENTS(AGENT_ID),
    TOOL_ID NUMBER REFERENCES TOOLS(TOOL_ID),
    PRIMARY KEY (AGENT_ID, TOOL_ID)
);

CREATE TABLE RUNS(
    RUN_ID NUMBER PRIMARY KEY,
    AGENT_ID NUMBER NOT NULL REFERENCES AGENTS(AGENT_ID),
    TASK_DESCRIPTION VARCHAR2(500) NOT NULL,
    START_TIME DATE NOT NULL,
    END_TIME DATE,
    STATUS VARCHAR2(20) CHECK (STATUS IN ('RUNNING','COMPLETED','FAILED','CANCELLED')),
    INPUT_TOKENS NUMBER CHECK (INPUT_TOKENS >= 0),
    OUTPUT_TOKENS NUMBER CHECK (OUTPUT_TOKENS >= 0),
    CHECK (END_TIME >= START_TIME),
    CHECK ((STATUS = 'RUNNING' AND END_TIME IS NULL) OR (STATUS <> 'RUNNING' AND END_TIME IS NOT NULL))
);

CREATE TABLE TOOL_CALLS(
    CALL_ID NUMBER PRIMARY KEY,
    RUN_ID NUMBER NOT NULL REFERENCES RUNS(RUN_ID),
    TOOL_ID NUMBER NOT NULL REFERENCES TOOLS(TOOL_ID),
    CALL_TIME DATE,
    CALL_INPUT VARCHAR2(500),
    DURATION_MS NUMBER CHECK (DURATION_MS >= 0),
    CALL_STATUS VARCHAR2(20) CHECK (CALL_STATUS IN ('SUCCESS','ERROR','TIMEOUT'))
);


