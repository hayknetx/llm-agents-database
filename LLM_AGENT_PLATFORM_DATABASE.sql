PRIMARY KEY (MODEL_ID);
ALTER TABLE AGENTS
ADD CONSTRAINT PK_AGENTS
PRIMARY KEY (AGENT_ID);
ALTER TABLE TOOLS
ADD CONSTRAINT PK_TOOLS
PRIMARY KEY (TOOL_ID);
-- Composite key: an agent can get each tool only once
ALTER TABLE AGENT_TOOLS
ADD CONSTRAINT PK_AGENT_TOOLS
PRIMARY KEY (AGENT_ID, TOOL_ID);
ALTER TABLE RUNS
ADD CONSTRAINT PK_RUNS
PRIMARY KEY (RUN_ID);
ALTER TABLE TOOL_CALLS
ADD CONSTRAINT PK_TOOL_CALLS
PRIMARY KEY (CALL_ID);

-- Foreign keys
ALTER TABLE AGENTS
ADD CONSTRAINT FK_AGENTS_USERS
FOREIGN KEY (USER_ID)
REFERENCES USERS(USER_ID);
ALTER TABLE AGENTS
ADD CONSTRAINT FK_AGENTS_MODELS
FOREIGN KEY (MODEL_ID)
REFERENCES MODELS(MODEL_ID);
ALTER TABLE AGENT_TOOLS
ADD CONSTRAINT FK_AGENT_TOOLS_AGENTS
FOREIGN KEY (AGENT_ID)
REFERENCES AGENTS(AGENT_ID);
ALTER TABLE AGENT_TOOLS
ADD CONSTRAINT FK_AGENT_TOOLS_TOOLS
FOREIGN KEY (TOOL_ID)
REFERENCES TOOLS(TOOL_ID);
ALTER TABLE RUNS
ADD CONSTRAINT FK_RUNS_AGENTS
FOREIGN KEY (AGENT_ID)
REFERENCES AGENTS(AGENT_ID);
ALTER TABLE TOOL_CALLS
ADD CONSTRAINT FK_TOOL_CALLS_RUNS
FOREIGN KEY (RUN_ID)
REFERENCES RUNS(RUN_ID);
ALTER TABLE TOOL_CALLS
ADD CONSTRAINT FK_TOOL_CALLS_TOOLS
FOREIGN KEY (TOOL_ID)
REFERENCES TOOLS(TOOL_ID);

-- Every agent must belong to a user and use a model; every run and call must point somewhere
ALTER TABLE AGENTS MODIFY (USER_ID NOT NULL);
ALTER TABLE AGENTS MODIFY (MODEL_ID NOT NULL);
ALTER TABLE RUNS MODIFY (AGENT_ID NOT NULL);
ALTER TABLE TOOL_CALLS MODIFY (RUN_ID NOT NULL);
ALTER TABLE TOOL_CALLS MODIFY (TOOL_ID NOT NULL);

-- UNIQUE and NOT NULL
ALTER TABLE USERS
ADD CONSTRAINT UQ_USERS_EMAIL
UNIQUE (EMAIL);
ALTER TABLE USERS MODIFY (EMAIL NOT NULL);
ALTER TABLE MODELS
ADD CONSTRAINT UQ_MODELS_NAME
UNIQUE (MODEL_NAME);
ALTER TABLE MODELS MODIFY (MODEL_NAME NOT NULL);
ALTER TABLE MODELS MODIFY (PROVIDER NOT NULL);
ALTER TABLE AGENTS MODIFY (AGENT_NAME NOT NULL);
ALTER TABLE TOOLS
ADD CONSTRAINT UQ_TOOLS_NAME
UNIQUE (TOOL_NAME);
ALTER TABLE TOOLS MODIFY (TOOL_NAME NOT NULL);
ALTER TABLE RUNS MODIFY (TASK_DESCRIPTION NOT NULL);
ALTER TABLE RUNS MODIFY (START_TIME NOT NULL);

-- CHECK constraints
ALTER TABLE MODELS
ADD CONSTRAINT CHK_MODELS_CONTEXT
CHECK (CONTEXT_WINDOW > 0);
ALTER TABLE MODELS
ADD CONSTRAINT CHK_MODELS_PRICES
CHECK (INPUT_PRICE >= 0 AND OUTPUT_PRICE >= 0);
ALTER TABLE AGENTS
ADD CONSTRAINT CHK_AGENTS_TEMPERATURE
CHECK (TEMPERATURE BETWEEN 0 AND 2);
ALTER TABLE TOOLS
ADD CONSTRAINT CHK_TOOLS_TYPE
CHECK (TOOL_TYPE IN ('SEARCH','CODE','DATABASE','API','FILE'));
ALTER TABLE RUNS
ADD CONSTRAINT CHK_RUNS_STATUS
CHECK (STATUS IN ('RUNNING','COMPLETED','FAILED','CANCELLED'));
ALTER TABLE RUNS
ADD CONSTRAINT CHK_RUNS_TOKENS
CHECK (INPUT_TOKENS >= 0 AND OUTPUT_TOKENS >= 0);
ALTER TABLE RUNS
ADD CONSTRAINT CHK_RUNS_TIMES
CHECK (END_TIME >= START_TIME);
-- A running run has no end time yet; a finished run must have one
ALTER TABLE RUNS
ADD CONSTRAINT CHK_RUNS_END_STATUS
CHECK ((STATUS = 'RUNNING' AND END_TIME IS NULL)
    OR (STATUS <> 'RUNNING' AND END_TIME IS NOT NULL));
ALTER TABLE TOOL_CALLS
ADD CONSTRAINT CHK_TOOL_CALLS_DURATION
CHECK (DURATION_MS >= 0);
ALTER TABLE TOOL_CALLS
ADD CONSTRAINT CHK_TOOL_CALLS_STATUS
CHECK (CALL_STATUS IN ('SUCCESS','ERROR','TIMEOUT'));


