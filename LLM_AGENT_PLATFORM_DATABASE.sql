-- =====================================================================
-- LLM AGENT PLATFORM DATABASE  (Oracle SQL)
-- Users build AI agents on top of language models, give the agents
-- tools, and run them on tasks. Every run and every tool call is logged.
-- Order: 1) tables  2) constraints  3) sample data  4) queries
-- =====================================================================


-- =====================================================================
-- 1. TABLES
-- =====================================================================

CREATE TABLE USERS(
    USER_ID NUMBER,
    FIRST_NAME VARCHAR2(30),
    LAST_NAME VARCHAR2(30),
    EMAIL VARCHAR2(255),
    REGISTRATION_DATE DATE
);

CREATE TABLE MODELS(
    MODEL_ID NUMBER,
    MODEL_NAME VARCHAR2(50),
    PROVIDER VARCHAR2(50),
    CONTEXT_WINDOW NUMBER,          -- max tokens the model can read at once
    INPUT_PRICE NUMBER(10,2),       -- USD per 1 million input tokens
    OUTPUT_PRICE NUMBER(10,2)       -- USD per 1 million output tokens
);

CREATE TABLE AGENTS(
    AGENT_ID NUMBER,
    USER_ID NUMBER,
    MODEL_ID NUMBER,
    AGENT_NAME VARCHAR2(50),
    SYSTEM_PROMPT VARCHAR2(1000),
    TEMPERATURE NUMBER(3,2),
    CREATED_DATE DATE
);

CREATE TABLE TOOLS(
    TOOL_ID NUMBER,
    TOOL_NAME VARCHAR2(50),
    DESCRIPTION VARCHAR2(255),
    TOOL_TYPE VARCHAR2(20)
);

CREATE TABLE AGENT_TOOLS(
    AGENT_ID NUMBER,
    TOOL_ID NUMBER
);

CREATE TABLE RUNS(
    RUN_ID NUMBER,
    AGENT_ID NUMBER,
    TASK_DESCRIPTION VARCHAR2(500),
    START_TIME TIMESTAMP,
    END_TIME TIMESTAMP,
    STATUS VARCHAR2(20),
    INPUT_TOKENS NUMBER,
    OUTPUT_TOKENS NUMBER
);

CREATE TABLE TOOL_CALLS(
    CALL_ID NUMBER,
    RUN_ID NUMBER,
    TOOL_ID NUMBER,
    CALL_TIME TIMESTAMP,
    CALL_INPUT VARCHAR2(500),
    DURATION_MS NUMBER,
    CALL_STATUS VARCHAR2(20)
);


-- =====================================================================
-- 2. CONSTRAINTS
