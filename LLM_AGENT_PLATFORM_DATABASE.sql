-- 3. QUERIES
-- 1. Agents with owner and model
SELECT A.AGENT_NAME, U.NAME, M.MODEL_NAME FROM AGENTS A
JOIN USERS U ON A.USER_ID = U.USER_ID JOIN MODELS M ON A.MODEL_ID = M.MODEL_ID;
-- 2. Tools of each agent
SELECT A.AGENT_NAME, T.TOOL_NAME FROM AGENT_TOOLS L
JOIN AGENTS A ON L.AGENT_ID = A.AGENT_ID JOIN TOOLS T ON L.TOOL_ID = T.TOOL_ID;
-- 3. Failed runs
SELECT * FROM RUNS WHERE STATUS = 'FAILED';
-- 4. Cost of each run in USD
SELECT R.TASK, R.TOKENS * M.PRICE / 1000000 AS COST_USD FROM RUNS R
JOIN AGENTS A ON R.AGENT_ID = A.AGENT_ID JOIN MODELS M ON A.MODEL_ID = M.MODEL_ID;
-- 5. Tool calls with task and tool name
SELECT C.CALL_ID, R.TASK, T.TOOL_NAME, C.STATUS FROM TOOL_CALLS C
JOIN RUNS R ON C.RUN_ID = R.RUN_ID JOIN TOOLS T ON C.TOOL_ID = T.TOOL_ID;
