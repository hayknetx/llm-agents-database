-- LLM AGENT PLATFORM DATABASE (Oracle SQL)

-- 1. TABLES
CREATE TABLE USERS (USER_ID NUMBER PRIMARY KEY, NAME VARCHAR2(50) NOT NULL, EMAIL VARCHAR2(100) NOT NULL UNIQUE);
CREATE TABLE MODELS (MODEL_ID NUMBER PRIMARY KEY, MODEL_NAME VARCHAR2(50) NOT NULL UNIQUE, PRICE NUMBER CHECK (PRICE >= 0));
CREATE TABLE AGENTS (AGENT_ID NUMBER PRIMARY KEY, AGENT_NAME VARCHAR2(50) NOT NULL,
    USER_ID NUMBER REFERENCES USERS(USER_ID), MODEL_ID NUMBER REFERENCES MODELS(MODEL_ID));
CREATE TABLE TOOLS (TOOL_ID NUMBER PRIMARY KEY, TOOL_NAME VARCHAR2(50) NOT NULL UNIQUE);
CREATE TABLE AGENT_TOOLS (AGENT_ID NUMBER REFERENCES AGENTS(AGENT_ID), TOOL_ID NUMBER REFERENCES TOOLS(TOOL_ID),
    PRIMARY KEY (AGENT_ID, TOOL_ID));
CREATE TABLE RUNS (RUN_ID NUMBER PRIMARY KEY, AGENT_ID NUMBER REFERENCES AGENTS(AGENT_ID), TASK VARCHAR2(200) NOT NULL,
    TOKENS NUMBER CHECK (TOKENS >= 0), STATUS VARCHAR2(20) CHECK (STATUS IN ('COMPLETED', 'FAILED')));
CREATE TABLE TOOL_CALLS (CALL_ID NUMBER PRIMARY KEY, RUN_ID NUMBER REFERENCES RUNS(RUN_ID),
    TOOL_ID NUMBER REFERENCES TOOLS(TOOL_ID), STATUS VARCHAR2(20) CHECK (STATUS IN ('SUCCESS', 'ERROR')));

